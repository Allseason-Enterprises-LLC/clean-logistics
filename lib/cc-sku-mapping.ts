export function mapSku(ccSku: string, productName: string, qty: number): string | null {
  if (SKU_MAP[ccSku]) return SKU_MAP[ccSku];

  if (ccSku && !ccSku.startsWith('CN--')) return ccSku;

  if (productName) {
    for (const [name, skuMap] of Object.entries(NAME_TO_SKU)) {
      if (productName.toLowerCase().includes(name.toLowerCase())) {
        const packKey = String(qty || 1);
        return skuMap[packKey] || skuMap['1'];
      }
    }
  }

  return null;
}
